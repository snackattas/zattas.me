const fs = require('fs');
const path = require('path');

const galleryDir = path.join(__dirname, '..', 'scripts', 'gallery');
const outputFile = path.join(__dirname, '..', 'src', 'data', 'generatedGalleryScripts.ts');

const scripts = {};

try {
  const files = fs.readdirSync(galleryDir);

  files.forEach((file) => {
    const match = file.match(/^([a-z]+)-([a-z]+)-fun\.([a-z]+)$/);
    if (!match) return;

    const [, language, tool] = match;
    const filePath = path.join(galleryDir, file);
    const content = fs.readFileSync(filePath, 'utf-8');

    if (!scripts[tool]) {
      scripts[tool] = {};
    }
    scripts[tool][language] = content;
  });

  // Generate TypeScript file
  const tsContent = `// This file is auto-generated by scripts/generate-gallery-data.js
// Do not edit manually!

export interface GalleryScripts {
  [tool: string]: {
    [language: string]: string;
  };
}

export const galleryScripts: GalleryScripts = ${JSON.stringify(scripts, null, 2)};
`;

  fs.writeFileSync(outputFile, tsContent, 'utf-8');
  console.log('✓ Generated gallery scripts data');
} catch (error) {
  console.error('Failed to generate gallery scripts:', error);
  process.exit(1);
}
